#!/usr/bin/env python3
"""Render runners.yaml into deploy/runners/apps/*.yaml (one Argo Application per ARC scale set).

    python3 scripts/render_runners.py          # write
    python3 scripts/render_runners.py --check  # fail if the rendered files are stale

Requires PyYAML. The output is deterministic; never hand-edit deploy/runners/apps/.
"""
from __future__ import annotations

import argparse
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "deploy" / "runners" / "apps"
NAMESPACE = "ci-runners"
SOURCE = "https://github.com/jvallery/estate-ci.git"
SUFFIX = {"ci": "ci", "pg": "pg", "build": "build", "buildcheck": "buildcheck"}
# Extra ci-profile sets for repos whose checks need more than one CI image:
# profile key "ci-<variant>" renders set "<repo>-ci-<variant>" (a ci profile).
# A ci variant with "postgres: true" also gets the pg profile's Postgres sidecar.
CI_VARIANT = re.compile(r"^ci-[a-z0-9]{1,12}$")
DIGEST_REF = re.compile(r"^[a-z0-9.\-]+(:[0-9]+)?(/[a-z0-9._\-]+)+(:[A-Za-z0-9._\-]+)?@sha256:[0-9a-f]{64}$")
NAME = re.compile(r"^[a-z0-9]([a-z0-9-]{0,43}[a-z0-9])?$")
class _NoAliasDumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


HEADER = "# GENERATED by scripts/render_runners.py from runners.yaml. Do not edit.\n"


class RenderError(Exception):
    pass


def pinned(ref: str, what: str) -> str:
    if not DIGEST_REF.match(ref or ""):
        raise RenderError(f"{what}: {ref!r} is not a digest-pinned image reference")
    return ref


def res(cpu, mem, lcpu, lmem, eph="1Gi", leph="4Gi"):
    return {
        "requests": {"cpu": str(cpu), "memory": mem, "ephemeral-storage": eph},
        "limits": {"cpu": str(lcpu), "memory": lmem, "ephemeral-storage": leph},
    }


def restricted(uid: int | None = None) -> dict:
    sc = {"allowPrivilegeEscalation": False, "capabilities": {"drop": ["ALL"]}, "runAsNonRoot": True}
    if uid is not None:
        sc["runAsUser"] = uid
        sc["runAsGroup"] = uid
    return sc


TOOLBOX_CLIS = ("kubectl", "kustomize", "helm", "kubeconform", "yq")
# Copy the job image's passwd/group and add the job uid (and its gid) if absent.
NSS_SCRIPT = (
    'for f in passwd group; do if [ -r /etc/$f ]; then cat /etc/$f > /nss/$f; else : > /nss/$f; fi; done; '
    'cut -d: -f3 /nss/passwd | grep -qx "$JOB_UID" || '
    'echo "runner:x:$JOB_UID:$JOB_UID:estate-ci runner:/home/runner:/bin/sh" >> /nss/passwd; '
    'cut -d: -f3 /nss/group | grep -qx "$JOB_UID" || echo "runner:x:$JOB_UID:" >> /nss/group'
)


def pod_template(d: dict, profile: str, opts: dict, expected: str, base: str, label: str | None = None) -> dict:
    label = label or profile
    exchange = {"name": "exchange", "mountPath": "/exchange"}
    work = {"name": "work", "mountPath": "/home/runner/_work"}
    scripts = {"name": "estate-ci-scripts", "mountPath": "/opt/estate-ci", "readOnly": True}
    runner = {
        "name": "runner",
        # runner_image (ci profiles): a runner image built FROM the stock
        # actions-runner image with the repo's tools, so bare `run:` steps work
        # unchanged (a label-swap migration) without a job sidecar.
        "image": pinned(opts.get("runner_image", d["runner_image"]), "runner_image"),
        "command": ["/home/runner/run.sh"],
        "env": [
            {"name": "ACTIONS_RUNNER_HOOK_JOB_STARTED", "value": "/opt/estate-ci/job-started-guard.sh"},
            {"name": "CI_EXPECTED_REPOSITORY", "value": expected},
            {"name": "CI_RUNNER_PROFILE", "value": profile},
            {"name": "CI_EXCHANGE_DIR", "value": "/exchange"},
            {"name": "ESTATE_CI", "value": "/opt/estate-ci"},
        ],
        "resources": res("250m", "512Mi", "2", "2Gi", "1Gi", "16Gi"),
        "securityContext": restricted(1001),
        "volumeMounts": [work, exchange, scripts],
    }
    if profile == "ci" and not opts.get("job_image"):
        runner["resources"] = res("1", "1Gi", "4", "4Gi", "1Gi", "16Gi")
    if opts.get("runner_resources"):
        if profile != "ci":
            raise RenderError(f"{base}: runner_resources is only for ci profiles")
        rr = opts["runner_resources"]
        runner["resources"] = res(rr["cpu"], rr["memory"], rr["limit_cpu"], rr["limit_memory"], "1Gi", "16Gi")
    if opts.get("runner_image") and profile != "ci":
        raise RenderError(f"{base}: runner_image is only for ci profiles")
    containers = [runner]
    volumes = [
        {"name": "work", "emptyDir": {"sizeLimit": "16Gi"}},
        {"name": "exchange", "emptyDir": {"sizeLimit": "24Gi"}},
        {"name": "estate-ci-scripts", "configMap": {"name": "estate-ci-scripts", "defaultMode": 0o555}},
    ]

    def agent(name: str) -> list[dict]:
        return [{"name": "CI_SIDECAR_NAME", "value": name}, {"name": "CI_EXCHANGE_DIR", "value": "/exchange"}]

    init_containers: list[dict] = []
    if opts.get("job_image"):
        jr = opts.get("job_resources", {})
        uid = int(opts.get("job_uid", 1001))
        job_image = pinned(opts["job_image"], "job_image")
        # Runner-environment parity for arbitrary job images (verdify-platform
        # #1402, 2026-11-06), without rebuilding them:
        #  - nss: the image's own /etc/passwd and /etc/group plus an entry for
        #    the job uid when it has none (initdb and other getpwuid() callers
        #    refuse an unnamed uid). Built by the job image itself, as that uid.
        #  - tools: the toolbox's static Go CLIs (kubectl, kustomize, helm,
        #    kubeconform, yq; pinned and checksummed in the toolbox build),
        #    APPENDED to PATH by sidecar-agent.sh, so the image's own tools win.
        init_containers += [
            {
                "name": "estate-ci-tools",
                "image": pinned(d["toolbox"], "toolbox"),
                "command": ["/bin/sh", "-ec", "mkdir -p /tools/bin && cd /usr/local/bin && "
                            "cp " + " ".join(TOOLBOX_CLIS) + " /tools/bin/"],
                "resources": res("50m", "64Mi", "500m", "256Mi", "256Mi", "1Gi"),
                "securityContext": restricted(1001),
                "volumeMounts": [{"name": "estate-ci-tools", "mountPath": "/tools"}],
            },
            {
                "name": "estate-ci-nss",
                "image": job_image,
                "command": ["/bin/sh", "-ec", NSS_SCRIPT],
                "env": [{"name": "JOB_UID", "value": str(uid)}],
                "resources": res("50m", "32Mi", "500m", "128Mi", "64Mi", "256Mi"),
                "securityContext": restricted(uid),
                "volumeMounts": [{"name": "estate-ci-nss", "mountPath": "/nss"}],
            },
        ]
        containers.append({
            "name": "job",
            "image": job_image,
            "command": ["/bin/sh", "/opt/estate-ci/sidecar-agent.sh"],
            "env": agent("job"),
            "resources": res(jr.get("cpu", "250m"), jr.get("memory", "2Gi"), jr.get("limit_cpu", "16"),
                             jr.get("limit_memory", "6Gi"), "2Gi", "16Gi"),
            "securityContext": restricted(uid),
            "volumeMounts": [work, exchange, scripts,
                             {"name": "estate-ci-tools", "mountPath": "/opt/estate-ci-tools", "readOnly": True},
                             {"name": "estate-ci-nss", "mountPath": "/etc/passwd", "subPath": "passwd", "readOnly": True},
                             {"name": "estate-ci-nss", "mountPath": "/etc/group", "subPath": "group", "readOnly": True}],
        })
        volumes += [{"name": "estate-ci-tools", "emptyDir": {"sizeLimit": "1Gi"}},
                    {"name": "estate-ci-nss", "emptyDir": {"sizeLimit": "1Mi"}}]
    if profile == "pg" or (profile == "ci" and opts.get("postgres") is True):
        pr = opts.get("postgres_resources", {})
        containers.append({
            "name": "postgres",
            "image": pinned(opts.get("postgres_image", d["postgres_image"]), "postgres_image"),
            "command": ["/bin/sh", "-ec"],
            "args": [
                "bin=$(ls -d /usr/lib/postgresql/*/bin | sort -V | tail -1); "
                "$bin/initdb -D /pg/data -U postgres --auth=trust -E UTF8 >/dev/null; "
                "exec $bin/postgres -D /pg/data -k /pg -c listen_addresses=127.0.0.1 "
                "-c fsync=off -c full_page_writes=off -c synchronous_commit=off -c max_connections=200"
            ],
            "resources": res(pr.get("cpu", "1"), pr.get("memory", "2Gi"), pr.get("limit_cpu", "2"),
                             pr.get("limit_memory", "4Gi"), "1Gi", "2Gi"),
            "securityContext": restricted(26),
            "readinessProbe": {"tcpSocket": {"port": 5432}, "periodSeconds": 2},
            "volumeMounts": [{"name": "pg", "mountPath": "/pg"}],
        })
        volumes.append({"name": "pg", "emptyDir": {"sizeLimit": "10Gi"}})
    if profile in ("build", "buildcheck"):
        kr = opts.get("kaniko_resources", {})
        containers.append({
            "name": "kaniko",
            "image": pinned(opts.get("kaniko_image", d["kaniko_image"]), "kaniko_image"),
            "command": ["/busybox/sh", "/opt/estate-ci/sidecar-agent.sh"],
            "env": agent("kaniko") + [{"name": "PATH", "value": "/busybox:/kaniko:/usr/local/bin:/usr/bin:/bin"}],
            # Kaniko must run as root to unpack image layers. It keeps the default
            # capability set and RuntimeDefault seccomp, which Pod Security
            # "baseline" admits. It holds only the registry PULL credential.
            "resources": res(kr.get("cpu", "250m"), kr.get("memory", "2Gi"), kr.get("limit_cpu", "16"),
                             kr.get("limit_memory", "8Gi"), "8Gi", "40Gi"),
            "volumeMounts": [work, exchange, scripts,
                             {"name": "registry-pull", "mountPath": "/kaniko/.docker", "readOnly": True}],
        })
        volumes.append({"name": "registry-pull", "secret": {
            "secretName": "zot-pull", "items": [{"key": ".dockerconfigjson", "path": "config.json"}]}})
    if profile == "build":
        # The repo's own zot principal, mounted in the runner container only.
        # The job guard admits only default-branch push/dispatch on build sets.
        push_secret = opts.get("push_secret", f"zot-push-{base}")
        runner["volumeMounts"].append({"name": "zot-push", "mountPath": "/run/secrets/zot-push", "readOnly": True})
        volumes.append({"name": "zot-push", "secret": {
            "secretName": push_secret, "items": [{"key": ".dockerconfigjson", "path": "config.json"}]}})
    return {
        "metadata": {"labels": {"estate-ci.vallery.net/profile": label}},
        "spec": {
            "automountServiceAccountToken": False,
            "restartPolicy": "Never",
            # ci-runner (0, preemptionPolicy Never): runners never preempt (at
            # estate-default they preempted fleet runners mid-job, #33), and
            # default workloads cannot preempt them (at ci-preemptible, -1000,
            # they were preempted mid-job while workers sat at 99% memory).
            "priorityClassName": "ci-runner",
            "imagePullSecrets": [{"name": "zot-pull"}],
            "securityContext": {"fsGroup": 1001, "fsGroupChangePolicy": "OnRootMismatch",
                                "seccompProfile": {"type": "RuntimeDefault"}},
            # Soft spread only: a hard hostname spread strands runners (agents#5560).
            "topologySpreadConstraints": [{
                "maxSkew": 1, "topologyKey": "kubernetes.io/hostname", "whenUnsatisfiable": "ScheduleAnyway",
                "labelSelector": {"matchLabels": {"estate-ci.vallery.net/profile": label}}}],
            # avoid_nodes: soft preference only (weight 100), so runners still
            # land on a listed node when nothing else fits.
            **({"affinity": {"nodeAffinity": {"preferredDuringSchedulingIgnoredDuringExecution": [{
                "weight": 100, "preference": {"matchExpressions": [{
                    "key": "kubernetes.io/hostname", "operator": "NotIn",
                    "values": list(opts["avoid_nodes"])}]}}]}}} if opts.get("avoid_nodes") else {}),
            **({"initContainers": init_containers} if init_containers else {}),
            "containers": containers,
            "volumes": volumes,
        },
    }


def render(cfg: dict) -> dict[str, str]:
    d = cfg["defaults"]
    owners = cfg["owners"]
    out: dict[str, str] = {}
    for entry in cfg["sets"]:
        if "repo" in entry:
            owner, repo = entry["repo"].split("/", 1)
            base = re.sub(r"[^a-z0-9-]", "-", repo.lower())
            url = f"https://github.com/{owner}/{repo}"
            expected = f"{owner}/{repo}"
        else:
            owner = entry["org"]
            base = entry["name"]
            url = f"https://github.com/{owner}"
            expected = f"{owner}/*"
        if owner not in owners:
            raise RenderError(f"no registration secret for owner {owner}")
        for key, opts in (entry.get("profiles") or {}).items():
            profile = "ci" if CI_VARIANT.match(key) else key
            if profile not in SUFFIX:
                raise RenderError(f"{base}: unknown profile {key}")
            if profile == "build" and "repo" not in entry:
                # The push credential is per repository (ADR-0003); an org-wide
                # set would hand one repo's credential to every repo in the org.
                raise RenderError(f"{base}: the build profile needs a repo-level set")
            opts = opts or {}
            name = f"{base}-{key if profile != key else SUFFIX[profile]}"
            if not NAME.match(name):
                raise RenderError(f"scale set name {name!r} is invalid or longer than 45 characters")
            values = {
                "githubConfigUrl": url,
                "githubConfigSecret": owners[owner],
                "runnerScaleSetName": name,
                "minRunners": 0,
                "maxRunners": int(opts.get("max", d["max"][profile])),
                "controllerServiceAccount": d["controller_service_account"],
                "template": pod_template(d, profile, opts, expected, base, key),
            }
            app = {
                "apiVersion": "argoproj.io/v1alpha1",
                "kind": "Application",
                "metadata": {
                    "name": f"estate-ci-runner-{name}",
                    "namespace": "argocd",
                    "annotations": {"estate-ci.vallery.net/repository": expected},
                },
                "spec": {
                    "project": "estate-ci",
                    "source": {
                        "repoURL": "ghcr.io/actions/actions-runner-controller-charts",
                        "chart": "gha-runner-scale-set",
                        "targetRevision": d["chart_version"],
                        "helm": {"releaseName": name, "valuesObject": values},
                    },
                    "destination": {"server": "https://kubernetes.default.svc", "namespace": NAMESPACE},
                    "syncPolicy": {
                        "automated": {"prune": False, "selfHeal": True},
                        "syncOptions": ["ServerSideApply=true"],
                    },
                },
            }
            out[f"{name}.yaml"] = HEADER + yaml.dump(app, Dumper=_NoAliasDumper, sort_keys=False, width=200)
    names = sorted(out)
    out["kustomization.yaml"] = HEADER + yaml.safe_dump(
        {"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization", "resources": names},
        sort_keys=False)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    try:
        rendered = render(yaml.safe_load((ROOT / "runners.yaml").read_text()))
    except (RenderError, KeyError, ValueError) as exc:
        print(f"render_runners: {exc}", file=sys.stderr)
        return 2
    existing = {p.name: p.read_text() for p in OUT.glob("*.yaml")} if OUT.exists() else {}
    if args.check:
        if existing != rendered:
            stale = sorted(set(existing) ^ set(rendered) | {k for k in rendered if existing.get(k) != rendered[k]})
            print("render_runners: stale output, run scripts/render_runners.py: " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"render_runners: {len(rendered) - 1} scale sets up to date")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name in set(existing) - set(rendered):
        (OUT / name).unlink()
    for name, text in rendered.items():
        (OUT / name).write_text(text)
    print(f"render_runners: wrote {len(rendered) - 1} scale sets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
